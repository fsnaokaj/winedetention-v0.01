/* Live chat + per-offer comments + reactions. Logged-in members only. KV keys:
   wd:room:<room> (list of msg ids, newest first, max 200) · wd:msg (hash id->JSON) · wd:rx:<id> (hash emoji->count)
   wd:rxu:<id> (set sub|emoji, one reaction of each kind per member) · wd:banned (set of subs) · wd:rl:<sub> rate limit */
import { randomBytes } from "crypto";
import { r, pipe, obj } from "./redis.js";
import { SKUS } from "../../js/wd-catalog.js";
const E = (m, s = 400) => Object.assign(new Error(m), { status: s });
export const REACTIONS = ["🔥", "😂", "😍", "🎉", "👏", "💸"];
export const roomOk = (room) => room === "live" || room === "jukebox" || Object.prototype.hasOwnProperty.call(SKUS, room);
/* Basic filter: slurs/profanity list (masked), links, contact spam, shouting and repeat-spam. Kept short on purpose. */
const BAD = ["fuck", "shit", "bitch", "cunt", "nigg", "fag", "retard", "whore", "slut", "dick", "pussy", "cock", "asshole", "kys", "rape"];
const LINK = /(https?:\/\/|www\.|\b[a-z0-9-]+\.(com|net|io|xyz|gg|ly|me|co|app|link|site)\b|t\.me\/|discord\.gg)/i;
export function filterText(raw) {
  let t = String(raw ?? "").replace(/[\u0000-\u001f\u200b-\u200f<>]/g, "").replace(/\s+/g, " ").trim().slice(0, 240);
  if (!t) throw E("empty_message");
  if (LINK.test(t)) throw E("no_links");
  if (/(.)\1{9,}/.test(t)) throw E("spammy");
  if (/\b(dm me|whatsapp|telegram|onlyfans|free money|airdrop|seed phrase|private key)\b/i.test(t)) throw E("spammy");
  const letters = t.replace(/[^A-Za-z]/g, ""); if (letters.length > 12 && letters === letters.toUpperCase()) t = t.toLowerCase();
  for (const w of BAD) t = t.replace(new RegExp(w.split("").join("[^a-z]?") + "[a-z]*", "gi"), (m) => m[0] + "*".repeat(Math.max(2, m.length - 1)));
  return t;
}
export async function say(sub, h, room, text) {
  if (!roomOk(room)) throw E("bad_room");
  if (await r("SISMEMBER", "wd:banned", sub)) throw E("muted", 403);
  const clean = filterText(text);
  if (!(await r("SET", "wd:rl:" + sub, 1, "NX", "EX", 4))) throw E("slow_down", 429);
  const dk = `wd:rld:${sub}:${new Date().toISOString().slice(0, 10)}`; const n = await r("INCR", dk); if (n === 1) await r("EXPIRE", dk, 90000); if (n > 300) throw E("slow_down", 429);
  const last = await r("GET", "wd:last:" + sub); if (last && last === clean) throw E("duplicate");
  const m = { id: Date.now().toString(36) + randomBytes(3).toString("hex"), room, sub, handle: h.handle, member: +h.member || 0, avSeed: h.avSeed || h.handle, hasAv: +h.hasAv || 0, vip: h.vip || "", club: h.club || "", text: clean, at: Date.now() };
  await r("SET", "wd:last:" + sub, clean, "EX", 120); return post(m);
}
/** Gift/tip event shown in the room with an animation (text is generated by us, not user input). */
export async function sayGift(sub, h, room, g, to) {
  if (!roomOk(room)) room = "live";
  const m = { id: Date.now().toString(36) + randomBytes(3).toString("hex"), room, sub, handle: h.handle, member: +h.member || 0, avSeed: h.avSeed || h.handle, hasAv: +h.hasAv || 0, vip: h.vip || "", club: h.club || "", type: "gift", gift: g.id, to, text: `sent @${to} a ${g.name} ${g.emoji}`, at: Date.now() };
  return post(m);
}
async function post(m) {
  const room = m.room, clean = m.text;
  await pipe([["HSET", "wd:msg", m.id, JSON.stringify(m)], ["LPUSH", "wd:room:" + room, m.id], ["ZADD", "wd:msgs", m.at, m.id]]);
  const old = (await r("LRANGE", "wd:room:" + room, 200, -1)) || [];
  if (old.length) await pipe([["LTRIM", "wd:room:" + room, 0, 199], ["HDEL", "wd:msg", ...old], ["ZREM", "wd:msgs", ...old], ...old.map((id) => ["DEL", "wd:rx:" + id, "wd:rxu:" + id])]);
  return pubMsg(m, {});
}
const pubMsg = (m, rx) => ({ id: m.id, room: m.room, handle: m.handle, member: m.member, avSeed: m.avSeed, hasAv: m.hasAv, vip: m.vip, club: m.club || "", type: m.type || "", gift: m.gift || "", to: m.to || "", text: m.text, at: m.at, rx });
export async function feed(room, n = 40) {
  if (!roomOk(room)) throw E("bad_room");
  const ids = (await r("LRANGE", "wd:room:" + room, 0, n - 1)) || []; if (!ids.length) return [];
  const raws = await r("HMGET", "wd:msg", ...ids); const rxs = await pipe(ids.map((id) => ["HGETALL", "wd:rx:" + id]));
  return ids.map((id, i) => { try { return raws[i] ? pubMsg(JSON.parse(raws[i]), obj(rxs[i])) : null; } catch { return null; } }).filter(Boolean);
}
export async function react(sub, id, emoji) {
  if (!REACTIONS.includes(emoji)) throw E("bad_reaction");
  if (!/^[a-z0-9]{6,20}$/.test(String(id)) || !(await r("HEXISTS", "wd:msg", id))) throw E("not_found", 404);
  if (await r("SISMEMBER", "wd:banned", sub)) throw E("muted", 403);
  const added = await r("SADD", "wd:rxu:" + id, sub + "|" + emoji);
  if (added) await r("HINCRBY", "wd:rx:" + id, emoji, 1);
  return obj(await r("HGETALL", "wd:rx:" + id));
}
export async function delMsg(room, id) {
  const raw = await r("HGET", "wd:msg", id); const m = raw ? JSON.parse(raw) : null; const rm = room || (m && m.room);
  await pipe([["HDEL", "wd:msg", id], ["LREM", "wd:room:" + rm, 0, id], ["ZREM", "wd:msgs", id], ["DEL", "wd:rx:" + id], ["DEL", "wd:rxu:" + id]]);
  return m;
}
export async function recent(n = 100) { // admin moderation view across rooms
  const ids = (await r("ZREVRANGE", "wd:msgs", 0, n - 1)) || []; if (!ids.length) return [];
  const raws = await r("HMGET", "wd:msg", ...ids);
  return raws.map((x) => { try { return x ? JSON.parse(x) : null; } catch { return null; } }).filter(Boolean);
}
